// node src/data/generate-model-catalog-fallback.mjs [public-model_ui_catalog.json] [--check]
// Without a new public snapshot, retain the current offline IDs and UI overrides.
import { readFile, writeFile } from 'node:fs/promises';
import { MODEL_CATALOG_FALLBACK as previous } from './model-catalog-fallback.js';

const path = new URL('./model-catalog-fallback.js', import.meta.url);
const input = process.argv.slice(2).find(a => a !== '--check');
let rows = previous;
if (input) {
  const { models } = JSON.parse(await readFile(input, 'utf8'));
  if (!Array.isArray(models) || !models.length) throw new Error('Expected a nonempty public UI catalog');
  const local = new Map(previous.map(m => [m.id, m]));
  rows = models.map(m => ({ ...local.get(m.id), id: m.id, name: m.displayName, brand: m.brand,
    kind: m.image ? 'image' : m.video ? 'video' : local.get(m.id)?.kind || 'chat', vision: m.multimodal, thinking: m.enableThinking,
    costTier: m.costTier, customMultiplier: m.customMultiplier, proMaxOnly: m.proMaxOnly, proPlusOnly: m.proPlusOnly }));
}
const fields = ['id','name','brand','kind','vision','thinking','tools','costTier','customMultiplier','proMaxOnly','proPlusOnly','creditPerUse','promoLimited','promoTooltip','freeLimitNote'];
const filtered = rows.map(r => {
  if (typeof r.id !== 'string' || !r.id) throw new Error('Missing public model id');
  return Object.fromEntries(fields.filter(k => ['string','number','boolean'].includes(typeof r[k])).map(k => [k,r[k]]));
});
const output = '// Generated by generate-model-catalog-fallback.mjs; only public menu fields belong here.\n'
  + 'export const MODEL_CATALOG_FALLBACK = [\n' + filtered.map(r => '  ' + JSON.stringify(r)).join(',\n') + '\n];\n';
if (process.argv.includes('--check')) {
  if ((await readFile(path, 'utf8')).replace(/\r\n/g, '\n') !== output) throw new Error('Regenerate the public fallback');
} else await writeFile(path, output);
