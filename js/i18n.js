function renderInlineI18n(el, value) {
    const arrowHtml = '<span class="arrow-icon">↗</span>';
    if (!value.includes('<')) {
        el.textContent = value;
        return;
    }
    el.textContent = '';
    const parts = value.split(arrowHtml);
    parts.forEach((part, index) => {
        if (part) el.appendChild(document.createTextNode(part));
        if (index < parts.length - 1) {
            const span = document.createElement('span');
            span.className = 'arrow-icon';
            span.textContent = '↗';
            el.appendChild(span);
        }
    });
}

function translate(root = document) {
    const lang = localStorage.getItem('lang') || 'zh';
    const elements = root.querySelectorAll('[data-i18n]');
    elements.forEach(el => {
        const key = el.getAttribute('data-i18n');
        if (translations[lang] && translations[lang][key]) {
            const value = translations[lang][key];
            renderInlineI18n(el, value);
        }
    });

    // Translate placeholders
    const placeholderElements = root.querySelectorAll('[data-i18n-placeholder]');
    placeholderElements.forEach(el => {
        const key = el.getAttribute('data-i18n-placeholder');
        if (translations[lang] && translations[lang][key]) {
            el.placeholder = translations[lang][key];
        }
    });

    const questionElements = root.querySelectorAll('[data-i18n-question]');
    questionElements.forEach(el => {
        const key = el.getAttribute('data-i18n-question');
        if (translations[lang] && translations[lang][key]) {
            el.dataset.question = translations[lang][key];
        }
    });

    const ariaElements = root.querySelectorAll('[data-i18n-aria]');
    ariaElements.forEach(el => {
        const key = el.getAttribute('data-i18n-aria');
        if (translations[lang] && translations[lang][key]) {
            el.setAttribute('aria-label', translations[lang][key]);
        }
    });

    const contentElements = root.querySelectorAll('[data-i18n-content]');
    contentElements.forEach(el => {
        const key = el.getAttribute('data-i18n-content');
        if (translations[lang] && translations[lang][key]) {
            el.setAttribute('content', translations[lang][key]);
        }
    });

    const altElements = root.querySelectorAll('[data-i18n-alt]');
    altElements.forEach(el => {
        const key = el.getAttribute('data-i18n-alt');
        if (translations[lang] && translations[lang][key]) {
            el.setAttribute('alt', translations[lang][key]);
        }
    });

    const htmlElements = root.querySelectorAll('[data-i18n-html]');
    htmlElements.forEach(el => {
        const key = el.getAttribute('data-i18n-html');
        if (translations[lang] && translations[lang][key]) {
            el.innerHTML = translations[lang][key];
        }
    });

    const titleAttrElements = root.querySelectorAll('[data-i18n-title]');
    titleAttrElements.forEach(el => {
        const key = el.getAttribute('data-i18n-title');
        if (translations[lang] && translations[lang][key]) {
            el.setAttribute('title', translations[lang][key]);
        }
    });

    const titleEl = document.querySelector('title[data-i18n]');
    if (titleEl) {
        const titleKey = titleEl.getAttribute('data-i18n');
        if (translations[lang] && translations[lang][titleKey]) {
            document.title = translations[lang][titleKey];
        }
    }
}

function setLanguage(lang) {
    document.documentElement.lang = lang === 'zh' ? 'zh-CN' : 'en-US';
    localStorage.setItem('lang', lang);
    
    // Update active state of language selector if it exists
    const langToggle = document.getElementById('lang-toggle');
    if (langToggle) {
        const langLabel = langToggle.querySelector('.lang-label');
        if (langLabel) {
            langLabel.textContent = translations[lang]['footer.lang'];
        }
    }

    translate();

    if (window.AI_HERO && typeof window.AI_HERO.refreshLang === 'function') {
        window.AI_HERO.refreshLang(document.getElementById('aiInput'), lang);
    }

    // Trigger custom event for other scripts to react (e.g., article re-rendering)
    window.dispatchEvent(new CustomEvent('languageChanged', { detail: { lang } }));
}

async function initLanguage() {
    const savedLang = localStorage.getItem('lang');
    if (savedLang) {
        setLanguage(savedLang);
        return;
    }

    // Default from browser locale only; avoid third-party IP lookup.
    const navLang = navigator.language || navigator.userLanguage || 'en';
    const lang = navLang.toLowerCase().includes('zh') ? 'zh' : 'en';
    setLanguage(lang);
}

// Expose to window
window.translations = translations;
window.setLanguage = setLanguage;
window.initLanguage = initLanguage;
window.translate = translate;
